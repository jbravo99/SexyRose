#!/usr/bin/env python3
"""Pruebas de agenda, comisiones, asistente de soporte, WhatsApp y verificación automática."""
import asyncio
import pathlib
from playwright.async_api import async_playwright
R = []
def check(name, ok): R.append((name, bool(ok))); print(('OK  ' if ok else 'FAIL'), name)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(locale='es-AR', viewport={'width': 1280, 'height': 900})
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        # La ventana de +18 (agegate.js) tapa la página en cada pestaña nueva: se marca como aceptada antes de cargar.
        await pg.add_init_script("try { sessionStorage.setItem('hh_age_ok', '1'); } catch (e) {}")
        await pg.goto((pathlib.Path(__file__).resolve().parent / 'build' / 'full.html').as_uri()); await pg.wait_for_timeout(300)
        ev = pg.evaluate
        # Agenda: bloqueo excluye horarios
        await ev("HH.login('u_vale')")
        n = await ev("""(() => { const p = HH.profileOf('u_vale'); let d = null; for (let i=2;i<14;i++){ const y = HH.localDay(HH.daysFromNow(i)); if (HH.bookingSlots(p,y,1).length>3){ d=y; break; } }
          const before = HH.bookingSlots(p,d,1).length; HH.addBlock(p,{date:d,from:'00:00',to:'24:00',kind:'ocupado',allDay:true}); const after = HH.bookingSlots(p,d,1).length; return [before, after]; })()""")
        check('bloqueo de todo el día deja sin horarios', n[0] > 0 and n[1] == 0)
        await ev("HH.go('#panel.agenda')"); await pg.wait_for_timeout(300)
        check('calendario semanal visible', await pg.query_selector('.ag-grid') is not None)
        check('no hábil / ocupado en leyenda', 'No hábil' in await pg.inner_text('.ag-legend'))
        # Opt-in
        await ev("HH.logout(); HH.login('u_agus'); HH.go('#panel.agenda')"); await pg.wait_for_timeout(300)
        txt = await pg.inner_text('#app')
        check('agenda pregunta si la va a usar', '¿Vas a usar la agenda?' in txt)
        await pg.click('[data-action=dashAgendaOn]'); await pg.wait_for_timeout(300)
        check('activar agenda muestra configuración', await pg.query_selector('#dashBkForm') is not None)
        # Comisiones
        await ev("HH.saveSettings({ commission: { pack: 20, request: 15 } })")
        r = await ev("(() => { const pay = HH.pay({ userId: 'u_cliente', amountUsd: 50, type: 'pack', description: 'x', workerId: 'u_vale' }); const pay2 = HH.pay({ userId: 'u_cliente', amountUsd: 10, type: 'one_time', description: 'y', workerId: 'u_vale' }); return [pay.feePct, pay.feeUsd, pay.netUsd, pay2.feeUsd || 0]; })()")
        check('comisión de pack 20% guardada en la venta', r == [20, 10, 40, 0])
        await ev("HH.logout(); HH.login('u_vale'); HH.go('#panel.ingresos')"); await pg.wait_for_timeout(300)
        check('ingresos muestran comisión', 'comisión 20%' in await pg.inner_text('#app'))
        # Asistente de soporte
        await ev("HH.logout(); HH.login('u_cliente'); HH.go('#inicio')"); await pg.wait_for_timeout(300)
        check('botón Ayuda visible', await pg.is_visible('#supFab'))
        await pg.click('#supFab'); await pg.fill('#supTxt', 'cómo funciona el reembolso del chat en vivo'); await pg.press('#supTxt', 'Enter'); await pg.wait_for_timeout(200)
        check('asistente responde con la base', 'te reembolsamos automáticamente' in await pg.inner_text('#supPanel'))
        await pg.click('[data-action=supHuman]'); await pg.wait_for_timeout(200)
        tid = await ev("HH.ui.sup.ticketId")
        check('escala y crea consulta', bool(tid))
        await ev("HH.go('#chat.u_vale')"); await pg.wait_for_timeout(300)
        check('Ayuda oculto en chat', not await pg.is_visible('#supFab'))
        # Admin soporte
        await ev(f"HH.logout(); HH.login('u_admin'); HH.ui.admOps.tf='abierto'; HH.ui.admOps.tk='{tid}'; HH.go('#admin.soporte')"); await pg.wait_for_timeout(300)
        await pg.fill('#opsRep', 'Hola, ya lo revisamos.'); await pg.click('[data-submit=opsTkReply] button[type=submit]'); await pg.wait_for_timeout(200)
        st = await ev(f"HH.db.support.find(t=>t.id==='{tid}').status")
        check('admin responde consulta', st == 'respondido')
        await ev("HH.logout(); HH.login('u_cliente'); HH.go('#inicio')"); await pg.wait_for_timeout(300)
        check('respuesta del equipo aparece en el asistente', 'ya lo revisamos' in await pg.inner_text('#supPanel'))
        # WhatsApp: aviso de reserva nueva y respuesta
        bid = await ev("""(() => { const p = HH.profileOf('u_vale'); for (let i=1;i<20;i++){ const y = HH.localDay(HH.daysFromNow(i)); const s = HH.bookingSlots(p,y,1); if (s.length){ const r = HH.createBooking({ workerId:'u_vale', clientId:'u_cliente', activity:'cafe', place:'Café Tortoni', date:y, start:s[0], hours:1 }); return r.booking && r.booking.id; } } })()""")
        last = await ev(f"(() => {{ const t = HH.waThread('u_vale'); const m = t.messages[t.messages.length-1]; return m.ref && m.ref.id === '{bid}' && m.buttons.length === 3; }})()")
        check('nueva reserva llega por WhatsApp con botones', last)
        await ev("HH.logout(); HH.login('u_admin'); HH.ui.admOps.wt = HH.waThread('u_vale').id; HH.go('#admin.whatsapp')"); await pg.wait_for_timeout(300)
        await pg.click(f"[data-action=waBtn][data-b=bk_alt] >> nth=-1"); await pg.wait_for_timeout(300)
        alt = await pg.query_selector("[data-action=waBtn][data-b^='alt:2']")
        check('proponer otro horario ofrece opciones libres', alt is not None)
        if alt: await alt.click(); await pg.wait_for_timeout(300)
        prop = await ev(f"!!HH.db.bookings.find(b=>b.id==='{bid}').proposal")
        check('propuesta guardada en la reserva', prop)
        await ev("HH.logout(); HH.login('u_cliente'); HH.go('#cuenta.reservas')"); await pg.wait_for_timeout(300)
        await pg.click(f"[data-action=cliBkPropOk][data-id='{bid}']"); await pg.wait_for_timeout(300)
        moved = await ev(f"(() => {{ const b = HH.db.bookings.find(b=>b.id==='{bid}'); return !b.proposal; }})()")
        check('cliente acepta el cambio de horario', moved)
        # Confirmar por WhatsApp
        await ev("HH.logout(); HH.login('u_vale'); HH.go('#panel.agenda')"); await pg.wait_for_timeout(300)
        await pg.click('[data-action=waPreview]'); await pg.wait_for_timeout(300)
        btns = await pg.query_selector_all("#modalRoot [data-action=waBtn][data-b=bk_ok]"); btn = btns[-1] if btns else None
        if btn: await btn.click(); await pg.wait_for_timeout(300)
        st = await ev(f"HH.db.bookings.find(b=>b.id==='{bid}').status")
        check('acompañante confirma desde WhatsApp', st == 'confirmada')
        # Opt-in de agenda por WhatsApp
        await ev("(() => { const p = HH.profileOf('u_agus'); HH.bookingCfg(p).enabled = false; HH.waAskAgenda(p); })()")
        ok = await ev("""(() => { const t = HH.waThread('u_agus'); const m = t.messages[t.messages.length-1]; HH.waReply(t.id, m.id, 'ag_yes'); const m2 = t.messages[t.messages.length-1]; HH.waReply(t.id, m2.id, 'h_wk_15_21'); const c = HH.bookingCfg(HH.profileOf('u_agus')); return c.enabled && c.availability[1] && c.availability[1][0].from === '15:00'; })()""")
        check('activa agenda y horario hábil por WhatsApp', ok)
        # Soporte por WhatsApp (texto libre)
        ok = await ev("""(() => { const t = HH.waThread('wa_x', { name: '+54 9 11 1234-5678', phone: '+54 9 11 1234-5678', kind: 'cliente' }); HH.waReply(t.id, null, null, 'necesito hablar con una persona'); return !!t.ticketId && HH.db.support.some(k => k.id === t.ticketId && k.channel === 'whatsapp'); })()""")
        check('WhatsApp escala a soporte', ok)
        # Verificación automática
        ok = await ev("""(() => { const p = HH.profileOf('u_juli'); p.verified = 'pending'; p.verifiedBy = null; const auto = HH.onVerificationSent(p); return auto && p.verified === 'verified' && p.verifiedBy === 'ai'; })()""")
        check('verificación automática aprueba si coincide', ok)
        ok = await ev("""(() => { const p = HH.profileOf('u_mica'); p.verified = 'pending'; const auto = HH.onVerificationSent(p); return !auto && p.verified === 'pending' && p.aiReview.result === 'warn'; })()""")
        check('coincidencia baja queda para revisión manual', ok)
        ok = await ev("""(() => { const p = HH.profileOf('u_mica'); const age = p.age; p.age = 16; const r = HH.runAiReview(p); p.age = age; return r.result === 'fail'; })()""")
        check('documento menor de 18 bloquea', ok)
        await ev("HH.logout(); HH.login('u_admin'); HH.go('#admin.ajustes')"); await pg.wait_for_timeout(300)
        t = await pg.inner_text('#app')
        check('ajustes: comisiones, verificación, asistente y WhatsApp', all(x in t for x in ['Comisiones', 'Verificación automática', 'Asistente AI', 'Bot de WhatsApp']))
        # Estadísticas
        await ev("HH.logout(); HH.go('#inicio')"); await pg.wait_for_timeout(300)
        before = await ev("(() => { const b = (HH.profileOf('u_vale').statsDaily || {})[HH.localDay()] || {}; return [b.views || 0, (b.src || {}).inicio || 0, b.imp || 0, b.wa || 0]; })()")
        await ev("HH.go('#perfil.valentina')"); await pg.wait_for_timeout(300)
        await ev("HH.actions.pubInterest({ dataset: { id: 'u_vale' } })"); await pg.wait_for_timeout(300)
        await ev("(() => { const a = document.querySelector('#pubWaLink'); if (a) { a.removeAttribute('target'); a.setAttribute('href', '#'); a.click(); } })()"); await pg.wait_for_timeout(200)
        after = await ev("(() => { const b = (HH.profileOf('u_vale').statsDaily || {})[HH.localDay()] || {}; return [b.views || 0, (b.src || {}).inicio || 0, b.imp || 0, b.wa || 0]; })()")
        check('estadísticas: visita desde Inicio, aparición y clic a WhatsApp ' + str(before) + ' -> ' + str(after), after[0] == before[0] + 1 and after[1] == before[1] + 1 and after[2] >= 1 and after[3] == before[3] + 1)
        await ev("HH.closeModal(); HH.login('u_vale'); HH.go('#panel.estadisticas')"); await pg.wait_for_timeout(300)
        check('panel de estadísticas (Star)', await pg.query_selector('.st-chart') is not None)
        await ev("HH.logout(); HH.login('u_juli'); HH.go('#panel.estadisticas')"); await pg.wait_for_timeout(300)
        check('estadísticas bloqueadas en plan Oro', 'desde el plan Diamante' in await pg.inner_text('#app'))
        ranks = await ev("HH.storyOrder().map(p => HH.LEVELS[HH.levelOf(p.userId)] ? HH.LEVELS[HH.levelOf(p.userId)].rank : 0)")
        check('historias ordenadas por categoría ' + str(ranks), ranks == sorted(ranks, reverse=True))
        only = await ev("(() => { HH.ui.city = 'Argentina'; return HH.storyOrder().every(p => HH.inCity(p, 'Argentina')); })()")
        check('historias: solo las del país elegido', only)
        # Intereses (Sobre mí)
        await ev("HH.logout(); HH.ui.city = undefined; HH.go('#perfil.valentina')"); await pg.wait_for_timeout(300)
        about = await ev("[...document.querySelectorAll('.pf-about dt')].map(x => x.textContent)")
        check('Sobre mí muestra Intereses y no Salidas', 'Intereses' in about and 'Salidas' not in about)
        await ev("HH.login('u_admin'); HH.go('#admin.categorias')"); await pg.wait_for_timeout(300)
        check('admin: lista de intereses', await pg.query_selector('#admIntCard .adm-int') is not None)
        await ev("HH.actions.admIntEdit({ dataset: {} })"); await pg.wait_for_timeout(150)
        await ev("document.getElementById('intL').value = 'Astronomía'; document.getElementById('intEn').value = 'Astronomy'; document.querySelector('#modalBox [data-modal-action=\"1\"]').click()"); await pg.wait_for_timeout(200)
        check('admin: crear interés', await ev("!!HH.interestById('astronomia') && HH.interestLabel('astronomia', 'en') === 'Astronomy'"))
        await ev("HH.logout(); HH.login('u_vale'); HH.go('#panel.perfil')"); await pg.wait_for_timeout(400)
        await ev("document.querySelector('#dashInts .chip[data-id=astronomia]').click(); document.querySelector('form[data-submit=dashSaveProfile]').requestSubmit()"); await pg.wait_for_timeout(300)
        check('acompañante elige interés (máx. 6)', await ev("(() => { const i = HH.profileBySlug('valentina').interests; return i.length <= 6; })()"))
        check('sin errores de JS', not errs)
        if errs: print(errs[:3])
        await b.close()
    print('OK', sum(1 for _, o in R if o), 'FAIL', [n for n, o in R if not o])
asyncio.run(main())
